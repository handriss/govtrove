// Label returns the human-readable title for any PSC key. Falls back to the key itself.
func Label(key string) string {
	if title, ok := codes[key]; ok {
		return title
	}
	if title, ok := groups[key]; ok {
		return title
	}
	if title, ok := categories[key]; ok {
		return title
	}
	return key
}

// ParentOf returns the hub key and title a 4-character code belongs under: its
// 2-character group when one is defined, otherwise its single-letter category.
// ok is false for the handful of codes with neither.
func ParentOf(code string) (key, title string, ok bool) {
	if len(code) < 2 {
		return "", "", false
	}
	if title, found := groups[code[:2]]; found {
		return code[:2], title, true
	}
	if title, found := categories[code[:1]]; found {
		return code[:1], title, true
	}
	return "", "", false
}

// Codes returns a copy of the 4-character PSC code-to-title map.
func Codes() map[string]string {
	m := make(map[string]string, len(codes))
	for k, v := range codes {
		m[k] = v
	}
	return m
}

// Hubs returns every parent key that at least one 4-character code hangs off,
// mapped to its title — the 2-character groups and single-letter categories in use.
func Hubs() map[string]string {
	m := make(map[string]string)
	for code := range codes {
		if key, title, ok := ParentOf(code); ok {
			m[key] = title
		}
	}
	return m
}
